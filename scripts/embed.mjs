#!/usr/bin/env node
/**
 * Embeds the data files as TypeScript modules (src/data/generated/), so the
 * built package carries its data inside its code — no file reads, no JSON
 * import attributes, and each authority's entry point carries only its own.
 *
 * The JSON files under data/ and certification.json stay the source of
 * truth: apps read them from the repository as a feed (see README, "Keeping
 * an app current"). This only copies them into the code. Runs before every
 * build, test and check (the npm `pre` scripts).
 *
 *   node scripts/embed.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'data', 'generated');

/** module name → [source file, type] */
const FILES = {
  swedenPlaces: ['data/places/islamiskaForbundetCoords.json', 'Record<string, { lat: number; lng: number }>'],
  diyanetWorldPoints: [
    'data/places/diyanetWorldPoints.json',
    'Record<string, { name: string; country: string; tz: string; ishaDeg: number; lat: number; lon: number; clock?: [string, number][] }>',
  ],
  diyanetTurkeyPoints: [
    'data/places/diyanetTurkeyPoints.json',
    'Record<string, { name: string; country: string; region?: string; years: Record<string, [number, number][]> }>',
  ],
  diyanetCountries: ['data/places/diyanetCountries.json', 'Record<string, { name: string; iso: string }>'],
  moroccoCities: [
    'data/places/moroccoCities.json',
    '{ id: number; name: string; lat: number | null; lng: number | null; heightM?: number }[]',
  ],
  moroccoMethodPoints: ['data/places/moroccoMethodPoints.json', 'Record<string, number[]>'],
  algeriaCities: ['data/places/algeriaCities.json', '{ id: number; name: string; nameEn?: string; lat: number; lon: number }[]'],
  algeriaMethodPoints: ['data/places/algeriaMethodPoints.json', 'Record<string, [number, number]>'],
  kemenagPlaces: ['data/places/kemenagPlaces.json', '{ id: number; name: string; nameEn?: string; lat: number; lon: number }[]'],
  kemenagMethodPoints: ['data/places/kemenagMethodPoints.json', 'Record<string, number[]>'],
  countryOutlines: ['data/locate/countryOutlines.json', '{ scale: number; countries: Record<string, number[][][]> }'],
};
for (const a of ['sweden', 'diyanet', 'morocco', 'algeria', 'indonesia']) {
  FILES[`${a}Corrections`] = [`data/corrections/${a}.json`, 'CorrectionsFile'];
}

fs.mkdirSync(OUT, { recursive: true });
const written = new Set();
const write = (name, body) => {
  const f = path.join(OUT, `${name}.ts`);
  const text = `// Generated by scripts/embed.mjs — do not edit; edit the JSON under data/ instead.\n${body}`;
  if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text) fs.writeFileSync(f, text);
  written.add(`${name}.ts`);
};

for (const [name, [src, type]] of Object.entries(FILES)) {
  const json = JSON.parse(fs.readFileSync(path.join(ROOT, src), 'utf8'));
  const imports = type === 'CorrectionsFile' ? `import type { CorrectionsFile } from '../../core/types.js';\n` : '';
  // `as unknown as`: a type assertion, not an annotation — a literal this size is
  // not for TypeScript's excess-property checks, and the data has extra fields.
  write(name, `${imports}const data = ${JSON.stringify(json)} as unknown as ${type};\nexport default data;\n`);
}

// certification.json, one module per authority (an entry point carries only its own)
const cert = JSON.parse(fs.readFileSync(path.join(ROOT, 'certification.json'), 'utf8'));
for (const a of ['sweden', 'diyanet', 'morocco', 'algeria', 'indonesia']) {
  write(
    `${a}Certification`,
    `import type { Certification } from '../../core/types.js';\nconst data: Certification | null = ${JSON.stringify(cert[a] ?? null)};\nexport default data;\n`,
  );
}

for (const f of fs.readdirSync(OUT)) if (!written.has(f)) fs.unlinkSync(path.join(OUT, f));
